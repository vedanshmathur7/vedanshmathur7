"""assets/htop-{dark,light}.svg — generated from data/now.yml.

Edit the YAML, never the SVG. Running (R) rows pulse around their cpu value.
"""
import yaml

from svgkit import ROOT, THEMES, T, document, esc, mono_w, write

W = 860
PAD = 20
FS = 13.5
CW = FS * 0.6
ROW_H = 25
STATE_LABEL = {"R": "running", "S": "sleeping", "I": "idle", "Z": "zombie"}


def load():
    data = yaml.safe_load((ROOT / "data" / "now.yml").read_text())
    procs = data["processes"]
    for p in procs:
        p["state"] = str(p.get("state", "S")).upper()[:1]
        p["cpu"] = max(0, min(100, float(p.get("cpu", 0))))
    return procs


def clip(s: str, n: int) -> str:
    return s if len(s) <= n else s[: n - 1] + "…"


def build(mode: str, procs) -> str:
    t = THEMES[mode]
    dark = mode == "dark"
    o = []
    n = len(procs)
    running = sum(p["state"] == "R" for p in procs)
    total = min(100.0, sum(p["cpu"] for p in procs))
    load1 = sum(p["cpu"] for p in procs if p["state"] == "R") / 100

    top_h = 70
    head_y = top_h + 8
    rows_y = head_y + 41
    H = int(rows_y + n * ROW_H + 40)

    o.append(f'<rect width="{W}" height="{H}" rx="6" fill="{t["bg"]}"/>')
    o.append(f'<rect x=".5" y=".5" width="{W-1}" height="{H-1}" rx="6" fill="none" stroke="{t["line"]}"/>')
    o.append("<defs>"
             f'<pattern id="bars" width="4" height="10" patternUnits="userSpaceOnUse">'
             f'<rect width="2.4" height="10" fill="{t["accent"]}"/></pattern>'
             f'<pattern id="barsd" width="4" height="10" patternUnits="userSpaceOnUse">'
             f'<rect width="2.4" height="10" fill="{t["dim"]}"/></pattern>'
             "</defs>")

    # ---- meters
    my = 34
    mx = PAD
    o.append(T(mx, my, "CPU", fill=t["accent"], size=FS, extra='font-weight="600"'))
    bx0 = mx + 3 * CW
    o.append(T(bx0, my, "[", fill=t["text"], size=FS, extra='font-weight="700"'))
    bar_x, bar_w = bx0 + CW + 2, 300
    o.append(f'<rect x="{bar_x}" y="{my-10}" width="{bar_w}" height="11" fill="url(#bars)" opacity=".14"/>')
    o.append(f'<rect class="mb" x="{bar_x}" y="{my-10}" width="{bar_w}" height="11" fill="url(#bars)" '
             f'style="transform:scaleX({total/100:.3f})"/>')
    o.append(T(bar_x + bar_w + 8, my, f"{total:.1f}%", fill=t["dim"], size=FS))
    o.append(T(bar_x + bar_w + 8 + mono_w(f"{total:.1f}%", FS) + 2, my, "]", fill=t["text"], size=FS, extra='font-weight="700"'))
    o.append(T(mx, my + 22, "src", fill=t["accent"], size=FS, extra='font-weight="600"'))
    o.append(T(mx + 4 * CW, my + 22, "data/now.yml  ·  regenerated by actions", fill=t["dim"], size=FS))

    rx = 520
    o.append(f'<text x="{rx}" y="{my}" font-size="{FS}" fill="{t["dim"]}">Tasks: '
             f'<tspan fill="{t["text"]}" font-weight="600">{n}</tspan>, '
             f'<tspan fill="{t["accent"]}" font-weight="600">{running}</tspan> running</text>')
    o.append(f'<text x="{rx}" y="{my+22}" font-size="{FS}" fill="{t["dim"]}">Load average: '
             f'<tspan fill="{t["text"]}" font-weight="600">{load1:.2f}</tspan> '
             f'{load1*0.86:.2f} {load1*0.71:.2f}</text>')

    # ---- header bar
    o.append(f'<rect x="10" y="{head_y}" width="{W-20}" height="21" fill="{t["accent"]}"/>')
    col_pid_end = PAD + 6 * CW
    col_s = col_pid_end + 2 * CW
    col_cpu_end = col_s + 8 * CW
    bar0, barw = col_cpu_end + 14, 120
    col_cmd = bar0 + barw + 22
    desc_x = col_cmd + 17 * CW
    max_desc = int((W - PAD - desc_x) / CW)
    hy = head_y + 15
    hdr = [(col_pid_end, "PID", "end"), (col_s, "S", None), (col_cpu_end, "CPU%", "end"),
           (bar0, "LOAD", None), (col_cmd, "Command", None)]
    for x, s, a in hdr:
        o.append(T(x, hy, s, fill=t["on_accent"], size=FS, anchor=a, extra='font-weight="700"'))

    # ---- rows
    css_rows = []
    for i, p in enumerate(procs):
        y = rows_y + i * ROW_H
        st = p["state"]
        live = st == "R"
        g = [f'<g class="row" style="animation-delay:{0.15 + i * 0.07:.2f}s">']
        if i == 0:
            g.append(f'<rect x="10" y="{y-17}" width="{W-20}" height="{ROW_H-1}" fill="{t["line"]}" opacity="{.45 if dark else .5}"/>')
        g.append(T(col_pid_end, y, str(p["pid"])[:6], fill=t["dim"], size=FS, anchor="end"))
        g.append(T(col_s, y, st, fill=t["accent"] if live else t["dim"], size=FS, extra='font-weight="700"'))
        g.append(T(col_cpu_end, y, f'{p["cpu"]:.1f}', fill=t["text"] if live else t["dim"], size=FS, anchor="end"))
        g.append(f'<rect x="{bar0}" y="{y-10}" width="{barw}" height="10" fill="url(#barsd)" opacity=".25"/>')
        v = max(p["cpu"], 1.5) / 100
        g.append(f'<rect class="b{i}" x="{bar0}" y="{y-10}" width="{barw}" height="10" '
                 f'fill="url(#{"bars" if live else "barsd"})" style="transform:scaleX({v:.3f})"/>')
        g.append(T(col_cmd, y, clip(str(p["name"]), 16), fill=t["text"] if live else t["dim"], size=FS,
                   extra='font-weight="600"'))
        g.append(T(desc_x, y, clip(str(p.get("desc", "")), max_desc), fill=t["dim"], size=FS))
        g.append("</g>")
        o.append("".join(g))
        if live:
            lo, hi = max(v * 0.7, 0.015), min(v * 1.25 + 0.03, 1)
            dur = 2.2 + (i * 0.53) % 1.6
            css_rows.append(
                f".b{i}{{animation:p{i} {dur:.2f}s ease-in-out {0.6 + i*0.2:.2f}s infinite alternate}}"
                f"@keyframes p{i}{{0%{{transform:scaleX({v:.3f})}}35%{{transform:scaleX({hi:.3f})}}"
                f"70%{{transform:scaleX({lo:.3f})}}100%{{transform:scaleX({v:.3f})}}}}")

    # ---- function-key bar
    fy = H - 14
    keys = [("F1", "whoami"), ("F2", "now.yml"), ("F5", "tree"), ("F6", "sort:cpu"), ("F9", "kill -9"), ("F10", "return 0")]
    x = 10
    for k, lab in keys:
        o.append(T(x, fy, k, fill=t["text"], size=12.5, extra='font-weight="700"'))
        x += mono_w(k, 12.5) + 1
        lw = mono_w(lab, 12.5) + 10
        o.append(f'<rect x="{x}" y="{fy-12.5}" width="{lw}" height="17" fill="{t["accent"]}" opacity="{.16 if dark else .14}"/>')
        o.append(T(x + 5, fy, lab, fill=t["accent"], size=12.5))
        x += lw + 10
    legend = "  ".join(f"{k}={v}" for k, v in STATE_LABEL.items())
    o.append(T(W - PAD, fy, legend, fill=t["mute"] if dark else t["dim"], size=11.5, anchor="end"))

    css = (".mb,[class^=b]{transform-box:fill-box;transform-origin:left center}"
           ".mb{animation:mb 3.1s ease-in-out .8s infinite alternate}"
           f"@keyframes mb{{0%{{transform:scaleX({total/100:.3f})}}50%{{transform:scaleX({max(total/100-.08,.05):.3f})}}100%{{transform:scaleX({total/100:.3f})}}}}"
           ".row{animation:up .35s ease-out both}" + "".join(css_rows))

    desc = "; ".join(f'{p["name"]} ({STATE_LABEL.get(p["state"], p["state"])}, {p["cpu"]:.0f}%): {p.get("desc","")}' for p in procs)
    return document(W, H, "".join(o), theme=t, fonts=("mono", "mono6", "mono7"), css=css,
                    title="$ htop — what Vedansh is running right now",
                    desc="htop-style process table. " + desc)


def main():
    procs = load()
    for m in ("dark", "light"):
        write(f"htop-{m}.svg", build(m, procs))


if __name__ == "__main__":
    main()
